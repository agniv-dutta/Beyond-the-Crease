interface Seed {
  id: string;
  name: string;
  teamId: string;
  role: Athlete['role'];
  captain?: boolean;
  country: string;
  region: string;
  languages: LanguageCode[];
  age: number;
  bio: string;
  quote: string;
  signature: SignatureStat;
  themes: Theme[];
  followers: number;
  momentum: number;
  featuredShare: number;
  visibilityScore: number;
  stats: AthleteStats;
  arc: ArcChapter[];
  gallery: { caption: string; tone: 'kesar' | 'rose' | 'pistachio' | 'mulberry' | 'pomelo' }[];
  initials?: string;
}

function initialsOf(name: string): string {
  const parts = name.split(' ');
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

function athlete(seed: Seed): Athlete {
  return {
    ...seed,
    initials: seed.initials ?? initialsOf(seed.name),
    sport: 'cricket',
    spotlightStoryIds: [],
  };
}

